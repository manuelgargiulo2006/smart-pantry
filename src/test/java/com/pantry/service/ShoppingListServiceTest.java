package com.pantry.service;

import com.pantry.model.Product;
import com.pantry.model.ShoppingListItem;
import com.pantry.model.StockThreshold;
import com.pantry.model.User;
import com.pantry.repository.*;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.ArgumentCaptor;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;

import java.time.LocalDate;
import java.util.Optional;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

/** Verifica la generazione automatica della lista della spesa. */
@ExtendWith(MockitoExtension.class)
class ShoppingListServiceTest {

    private static final Long USER = 1L;
    private static final Long PRODUCT = 10L;

    @Mock ShoppingListRepository shoppingListRepository;
    @Mock StockThresholdRepository thresholdRepository;
    @Mock PantryItemRepository pantryItemRepository;
    @Mock StockMovementRepository movementRepository;
    @Mock ProductRepository productRepository;
    @Mock UserRepository userRepository;

    @InjectMocks ShoppingListService service;

    private void threshold(int min) {
        StockThreshold t = new StockThreshold();
        t.setMinQuantity(min);
        when(thresholdRepository.findByUserIdAndProductId(USER, PRODUCT)).thenReturn(Optional.of(t));
    }

    @Test
    void sottoSogliaCreaLaVoceAutomaticaConLaQuantitaMancante() {
        threshold(5);
        when(pantryItemRepository.sumQuantity(USER, PRODUCT)).thenReturn(2L);
        when(shoppingListRepository.findFirstByUserIdAndProductIdAndBoughtFalse(USER, PRODUCT)).thenReturn(Optional.empty());
        when(userRepository.getReferenceById(USER)).thenReturn(new User());
        when(productRepository.getReferenceById(PRODUCT)).thenReturn(new Product());

        service.refreshProduct(USER, PRODUCT);

        ArgumentCaptor<ShoppingListItem> saved = ArgumentCaptor.forClass(ShoppingListItem.class);
        verify(shoppingListRepository).save(saved.capture());
        assertEquals(3, saved.getValue().getTargetQuantity());
        assertTrue(saved.getValue().isAutoGenerated());
    }

    @Test
    void sopraSogliaEliminaLaVoceAutomatica() {
        threshold(2);
        when(pantryItemRepository.sumQuantity(USER, PRODUCT)).thenReturn(4L);
        ShoppingListItem auto = new ShoppingListItem();
        auto.setAutoGenerated(true);
        when(shoppingListRepository.findFirstByUserIdAndProductIdAndBoughtFalse(USER, PRODUCT)).thenReturn(Optional.of(auto));

        service.refreshProduct(USER, PRODUCT);

        verify(shoppingListRepository).delete(auto);
    }

    @Test
    void leVociAggiunteAManoNonVengonoToccate() {
        threshold(2);
        when(pantryItemRepository.sumQuantity(USER, PRODUCT)).thenReturn(4L);
        ShoppingListItem manual = new ShoppingListItem();
        manual.setAutoGenerated(false);
        when(shoppingListRepository.findFirstByUserIdAndProductIdAndBoughtFalse(USER, PRODUCT)).thenReturn(Optional.of(manual));

        service.refreshProduct(USER, PRODUCT);

        verify(shoppingListRepository, never()).delete(any());
        verify(shoppingListRepository, never()).save(any());
    }

    @Test
    void laScadenzaPredefinitaUsaLaDurataDelProdotto() {
        Product latte = new Product();
        latte.setShelfLifeDays(7);
        LocalDate oggi = LocalDate.of(2026, 10, 8);
        assertEquals(LocalDate.of(2026, 10, 15), ShoppingListService.defaultExpiry(latte, oggi));

        Product senzaDurata = new Product();
        assertEquals(LocalDate.of(2026, 10, 15), ShoppingListService.defaultExpiry(senzaDurata, oggi));
    }
}
