package com.pantry.model;

import jakarta.persistence.*;

import java.time.LocalDateTime;

@Entity
@Table(name = "shopping_list")
public class ShoppingListItem {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "user_id", nullable = false)
    private User user;

    @ManyToOne(fetch = FetchType.EAGER, optional = false)
    @JoinColumn(name = "product_id", nullable = false)
    private Product product;

    @Column(name = "target_quantity", nullable = false)
    private Integer targetQuantity;

    @Column(name = "is_bought", nullable = false)
    private boolean bought;

    /** true se la voce è stata creata dal sistema perché il prodotto è sotto la soglia minima. */
    @Column(name = "auto_generated", nullable = false)
    private boolean autoGenerated;

    @Column(name = "created_at", nullable = false)
    private LocalDateTime createdAt;

    @Column(name = "bought_at")
    private LocalDateTime boughtAt;

    @PrePersist
    void onCreate() {
        if (createdAt == null) {
            createdAt = LocalDateTime.now();
        }
    }

    public ShoppingListItem() {
    }

    public Long getId() {
        return id;
    }

    public User getUser() {
        return user;
    }

    public Product getProduct() {
        return product;
    }

    public Integer getTargetQuantity() {
        return targetQuantity;
    }

    public boolean isBought() {
        return bought;
    }

    public boolean isAutoGenerated() {
        return autoGenerated;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public LocalDateTime getBoughtAt() {
        return boughtAt;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public void setUser(User user) {
        this.user = user;
    }

    public void setProduct(Product product) {
        this.product = product;
    }

    public void setTargetQuantity(Integer targetQuantity) {
        this.targetQuantity = targetQuantity;
    }

    public void setBought(boolean bought) {
        this.bought = bought;
    }

    public void setAutoGenerated(boolean autoGenerated) {
        this.autoGenerated = autoGenerated;
    }

    public void setCreatedAt(LocalDateTime createdAt) {
        this.createdAt = createdAt;
    }

    public void setBoughtAt(LocalDateTime boughtAt) {
        this.boughtAt = boughtAt;
    }
}
