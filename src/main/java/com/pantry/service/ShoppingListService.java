package com.pantry.service;

import com.pantry.model.*;
import com.pantry.repository.*;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.LocalDate;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.stream.Collectors;

/**
 * Lista della spesa. Le voci "automatiche" vengono create e aggiornate dal sistema
 * ogni volta che la quantità di un prodotto scende sotto la soglia minima dell'utente.
 */
@Service
public class ShoppingListService {

    private final ShoppingListRepository shoppingListRepository;
    private final StockThresholdRepository thresholdRepository;
    private final PantryItemRepository pantryItemRepository;
    private final StockMovementRepository movementRepository;
    private final ProductRepository productRepository;
    private final UserRepository userRepository;

    // ---------------------------------------------------------------- lettura

    @Transactional(readOnly = true)
    public List<ShoppingListItem> getOpenItems(Long userId) {
        return shoppingListRepository.findByUserIdAndBoughtFalseOrderByProductCategoryNameAscProductNameAsc(userId);
    }

    @Transactional(readOnly = true)
    public List<ShoppingListItem> getBoughtItems(Long userId) {
        return shoppingListRepository.findByUserIdAndBoughtTrueOrderByBoughtAtDesc(userId);
    }

    @Transactional(readOnly = true)
    public long countOpen(Long userId) {
        return shoppingListRepository.countByUserIdAndBoughtFalse(userId);
    }

    @Transactional(readOnly = true)
    public List<StockThreshold> getThresholds(Long userId) {
        return thresholdRepository.findByUserIdOrderByProductNameAsc(userId);
    }

    @Transactional(readOnly = true)
    public Integer getThresholdValue(Long userId, Long productId) {
        return thresholdRepository.findByUserIdAndProductId(userId, productId)
                .map(StockThreshold::getMinQuantity)
                .orElse(null);
    }

    /** Quantità totale di un prodotto nella dispensa dell'utente (somma di tutte le confezioni). */
    @Transactional(readOnly = true)
    public int getStock(Long userId, Long productId) {
        return (int) pantryItemRepository.sumQuantity(userId, productId);
    }

    // ---------------------------------------------------------------- generazione automatica

    /**
     * Confronta la scorta di un prodotto con la sua soglia minima e aggiorna la lista:
     * - sotto soglia: crea (o aggiorna) la voce automatica con la quantità che manca;
     * - di nuovo a posto: elimina la voce automatica non più necessaria.
     * Le voci aggiunte a mano dall'utente non vengono mai toccate.
     */
    @Transactional
    public void refreshProduct(Long userId, Long productId) {
        Integer min = getThresholdValue(userId, productId);
        int stock = getStock(userId, productId);
        var openItem = shoppingListRepository.findFirstByUserIdAndProductIdAndBoughtFalse(userId, productId);

        if (min != null && stock < min) {
            int missing = min - stock;
            if (openItem.isPresent()) {
                ShoppingListItem item = openItem.get();
                if (item.isAutoGenerated()) {
                    item.setTargetQuantity(missing);
                }
            } else {
                ShoppingListItem item = new ShoppingListItem();
                item.setUser(userRepository.getReferenceById(userId));
                item.setProduct(productRepository.getReferenceById(productId));
                item.setTargetQuantity(missing);
                item.setAutoGenerated(true);
                shoppingListRepository.save(item);
            }
        } else {
            openItem.filter(ShoppingListItem::isAutoGenerated).ifPresent(shoppingListRepository::delete);
        }
    }

    /** Ricontrolla tutte le soglie dell'utente. */
    @Transactional
    public void refreshAll(Long userId) {
        for (StockThreshold threshold : thresholdRepository.findByUserIdOrderByProductNameAsc(userId)) {
            refreshProduct(userId, threshold.getProduct().getId());
        }
    }

    // ---------------------------------------------------------------- soglie

    @Transactional
    public void setThreshold(Long userId, Long productId, int minQuantity) {
        if (!productRepository.existsById(productId)) {
            throw new NotFoundException("Prodotto non trovato");
        }
        StockThreshold threshold = thresholdRepository.findByUserIdAndProductId(userId, productId)
                .orElseGet(() -> {
                    StockThreshold t = new StockThreshold();
                    t.setUser(userRepository.getReferenceById(userId));
                    t.setProduct(productRepository.getReferenceById(productId));
                    return t;
                });
        threshold.setMinQuantity(minQuantity);
        thresholdRepository.save(threshold);
        refreshProduct(userId, productId);
    }

    @Transactional
    public void deleteThreshold(Long userId, Long thresholdId) {
        StockThreshold threshold = thresholdRepository.findByIdAndUserId(thresholdId, userId)
                .orElseThrow(() -> new NotFoundException("Soglia non trovata"));
        Long productId = threshold.getProduct().getId();
        thresholdRepository.delete(threshold);
        thresholdRepository.flush();
        refreshProduct(userId, productId);
    }

    // ---------------------------------------------------------------- voci manuali

    @Transactional
    public void addManual(Long userId, Long productId, int quantity) {
        if (!productRepository.existsById(productId)) {
            throw new NotFoundException("Prodotto non trovato");
        }
        var existing = shoppingListRepository.findFirstByUserIdAndProductIdAndBoughtFalse(userId, productId);
        if (existing.isPresent()) {
            ShoppingListItem item = existing.get();
            item.setTargetQuantity(item.getTargetQuantity() + quantity);
            item.setAutoGenerated(false);
        } else {
            ShoppingListItem item = new ShoppingListItem();
            item.setUser(userRepository.getReferenceById(userId));
            item.setProduct(productRepository.getReferenceById(productId));
            item.setTargetQuantity(quantity);
            item.setAutoGenerated(false);
            shoppingListRepository.save(item);
        }
    }

    @Transactional
    public void remove(Long userId, Long itemId) {
        ShoppingListItem item = getOwnItem(userId, itemId);
        shoppingListRepository.delete(item);
    }

    @Transactional
    public int clearBought(Long userId) {
        return shoppingListRepository.deleteBought(userId);
    }

    // ---------------------------------------------------------------- acquisto

    /**
     * Spunta un prodotto come comprato e lo riporta automaticamente in dispensa.
     * Se la scadenza non viene indicata si usa la durata media del prodotto (o 7 giorni).
     */
    @Transactional
    public PantryItem markBought(Long userId, Long itemId, Integer quantity, LocalDate expirationDate, Storage storage) {
        ShoppingListItem item = getOwnItem(userId, itemId);
        if (item.isBought()) {
            throw new BusinessException("\"" + item.getProduct().getName() + "\" è già stato segnato come comprato");
        }
        int bought = quantity == null || quantity < 1 ? item.getTargetQuantity() : quantity;
        LocalDate today = LocalDate.now();
        LocalDate expiry = expirationDate != null ? expirationDate : defaultExpiry(item.getProduct(), today);
        if (expiry.isBefore(today)) {
            throw new BusinessException("La data di scadenza non può essere già passata");
        }

        item.setBought(true);
        item.setBoughtAt(LocalDateTime.now());
        item.setTargetQuantity(bought);

        PantryItem pantryItem = new PantryItem();
        pantryItem.setUser(item.getUser());
        pantryItem.setProduct(item.getProduct());
        pantryItem.setQuantity(bought);
        pantryItem.setPurchaseDate(today);
        pantryItem.setExpirationDate(expiry);
        pantryItem.setStorage(storage == null ? Storage.DISPENSA : storage);
        pantryItemRepository.save(pantryItem);
        movementRepository.save(new StockMovement(item.getUser(), item.getProduct(), MovementType.ACQUISTATO, bought));

        pantryItemRepository.flush();
        refreshProduct(userId, item.getProduct().getId());
        return pantryItem;
    }

    public static LocalDate defaultExpiry(Product product, LocalDate from) {
        int days = product.getShelfLifeDays() != null ? product.getShelfLifeDays() : 7;
        return from.plusDays(days);
    }

    // ---------------------------------------------------------------- esportazione

    /** Lista in formato testo, raggruppata per categoria, pronta da salvare o condividere. */
    @Transactional(readOnly = true)
    public String exportText(Long userId, String username) {
        List<ShoppingListItem> items = getOpenItems(userId);
        StringBuilder sb = new StringBuilder();
        sb.append("LISTA DELLA SPESA - Smart Pantry\n");
        sb.append("Utente: ").append(username).append('\n');
        sb.append("Data: ").append(LocalDate.now().format(DateTimeFormatter.ofPattern("EEEE d MMMM yyyy", Locale.ITALY)))
          .append("\n\n");
        if (items.isEmpty()) {
            sb.append("La lista è vuota.\n");
            return sb.toString();
        }
        Map<String, List<ShoppingListItem>> byCategory = items.stream()
                .collect(Collectors.groupingBy(i -> i.getProduct().getCategory().getName(),
                        LinkedHashMap::new, Collectors.toList()));
        byCategory.forEach((category, list) -> {
            sb.append(category.toUpperCase(Locale.ITALY)).append('\n');
            for (ShoppingListItem i : list) {
                sb.append("[ ] ").append(i.getProduct().getName())
                  .append(" x").append(i.getTargetQuantity());
                if (i.isAutoGenerated()) {
                    sb.append("  (sotto la soglia minima)");
                }
                sb.append('\n');
            }
            sb.append('\n');
        });
        sb.append("Totale: ").append(items.size()).append(items.size() == 1 ? " prodotto" : " prodotti").append('\n');
        return sb.toString();
    }

    private ShoppingListItem getOwnItem(Long userId, Long itemId) {
        return shoppingListRepository.findByIdAndUserId(itemId, userId)
                .orElseThrow(() -> new NotFoundException("Voce della lista non trovata"));
    }

    public ShoppingListService(ShoppingListRepository shoppingListRepository, StockThresholdRepository thresholdRepository, PantryItemRepository pantryItemRepository, StockMovementRepository movementRepository, ProductRepository productRepository, UserRepository userRepository) {
        this.shoppingListRepository = shoppingListRepository;
        this.thresholdRepository = thresholdRepository;
        this.pantryItemRepository = pantryItemRepository;
        this.movementRepository = movementRepository;
        this.productRepository = productRepository;
        this.userRepository = userRepository;
    }
}
